"""Validated, secret-safe Docker Compose setup for a CPU worker.

The one-time token is returned in a separate .env, not embedded in the Compose
file. The administrator must protect and delete the generated .env after the
worker has enrolled. No shell script or arbitrary image is accepted.
"""
from __future__ import annotations

import json
import math
import os
import re
from urllib.parse import urlsplit
from typing import Any

IMAGE = "ghcr.io/lukacek/simple-aiproxy-worker:latest"
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$")


def validate_setup(data: dict[str, Any]) -> dict[str, Any]:
    if not isinstance(data, dict):
        raise ValueError("Invalid worker setup request")
    name = data.get("name", "my-compute-worker")
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        raise ValueError("name must contain 1-64 letters, digits, dashes or underscores")
    url = data.get("proxy_url", "")
    if (not isinstance(url, str) or len(url) > 250 or
            any(ord(char) <= 32 or ord(char) == 127 for char in url)):
        raise ValueError("Enter a public HTTPS origin without whitespace or control characters")
    parsed = urlsplit(url)
    if (parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password
            or parsed.query or parsed.fragment or parsed.path not in ("", "/")):
        raise ValueError("Proxy URL must be an HTTPS origin without credentials, query or path")
    try:
        _ = parsed.port
    except ValueError as exc:
        raise ValueError("Invalid proxy URL port") from exc
    memory = data.get("memory_gb", 4)
    disk = data.get("disk_gb", 8)
    threads = data.get("threads", 2)
    cpus = data.get("cpus", 2)
    for key, value, minimum, maximum in (
        ("memory_gb", memory, 2, 256), ("disk_gb", disk, 2, 2048),
        ("threads", threads, 1, 128)):
        if type(value) is not int or not minimum <= value <= maximum:
            raise ValueError(f"{key} must be an integer from {minimum} to {maximum}")
    if (not isinstance(cpus, (int, float)) or isinstance(cpus, bool)
            or not math.isfinite(cpus) or not 0.5 <= cpus <= 128):
        raise ValueError("cpus must be between 0.5 and 128")
    if threads > math.ceil(cpus):
        raise ValueError("threads must not exceed the configured CPU limit")
    return {"name": name, "proxy_url": url.rstrip("/"),
            "memory_gb": memory, "disk_gb": disk,
            "threads": threads, "cpus": float(cpus)}


def compose_text(settings: dict[str, Any]) -> str:
    """Canonical unprivileged worker Compose with no secrets."""
    name = json.dumps(settings["name"])
    proxy_env = "$" + "{SIMPLEAI_PROXY_URL:?Set the proxy URL in .env}"
    token_env = "$" + "{WORKER_ENROLLMENT_TOKEN:?Set an enrollment token in .env}"
    return (
        "# Generated by SimpleAI Proxy; review limits before starting.\n"
        "services:\n"
        "  compute-worker:\n"
        f"    image: {IMAGE}\n"
        "    restart: unless-stopped\n"
        "    init: true\n"
        "    read_only: true\n"
        "    cap_drop: [ALL]\n"
        "    security_opt: [no-new-privileges:true]\n"
        "    pids_limit: 256\n"
        f"    mem_limit: {settings['memory_gb']}g\n"
        f"    memswap_limit: {settings['memory_gb']}g\n"
        f"    cpus: {settings['cpus']}\n"
        "    environment:\n"
        f"      SIMPLEAI_PROXY_URL: {json.dumps(proxy_env)}\n"
        f"      WORKER_ENROLLMENT_TOKEN: {json.dumps(token_env)}\n"
        f"      WORKER_NAME: {name}\n"
        f"      WORKER_THREADS: {json.dumps(str(settings['threads']))}\n"
        f"      WORKER_DISK_LIMIT_GB: {json.dumps(str(settings['disk_gb']))}\n"
        "      WORKER_REASONING: 'on'\n"
        "    volumes:\n"
        "      - worker-data:/data\n"
        "      - worker-models:/models\n"
        "    tmpfs: [/tmp:size=128m]\n"
        "volumes:\n"
        "  worker-data:\n"
        "  worker-models:\n"
    )


def env_text(settings: dict[str, Any], token: str) -> str:
    if not isinstance(token, str) or not re.fullmatch(r"[A-Za-z0-9_-]{32,128}", token):
        raise ValueError("Invalid enrollment token")
    return (f"SIMPLEAI_PROXY_URL={settings['proxy_url']}\n"
            f"WORKER_ENROLLMENT_TOKEN={token}\n")
